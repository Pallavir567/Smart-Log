"""
AIT-LDS Label Configuration
============================
Single source of truth for label classification used in AIT Log Data Set
(fox, russellmitchell, santos scenarios).

All 22 labels found in these datasets are documented here with their
source rule, attack phase, and classification decision.

Labels are classified into THREE categories:
  ANOMALOUS  - confirmed attacker activity; train as is_anomaly=1
  UNCERTAIN  - labeled by dataset but meaning is ambiguous or borderline;
               preserved separately and NOT used for training by default
  (no BENIGN/BACKGROUND category exists in these datasets)

Reference: rules/ YAML files in each dataset folder.
Last audited: 2026-10-14
"""

from typing import Dict, FrozenSet

# ── ANOMALOUS labels ──────────────────────────────────────────────────────────
# Every label in this set describes confirmed attacker activity as documented
# in the dataset's rules/ YAML files. A log line carrying any of these labels
# is classified is_anomaly = 1.
#
# Source verification (from rules/ YAML descriptions):
#   attacker          — co-label with dnsteal; marks DNS queries to attacker-controlled subdomain
#   attacker_http     — HTTP traffic from attacker matched to Apache access logs
#   attacker_vpn      — OpenVPN connections from attacker IP (foothold/escalation phases)
#   attacker_change_user — /bin/su by attacker to hijack another user account
#   crack_passwords   — metricbeat logs during wpcrack execution time window
#   dirb              — Apache logs during dirb web directory brute-force execution
#   dns_scan          — DNS brute-force probe queries (random strings → attacker fingerprint)
#   dnsteal           — DNS queries/answers to attacker-controlled exfiltration subdomain
#   dnsteal-received  — dnsteal traffic during active exfiltration window
#   dnsteal-dropped   — dnsteal DNS retries after server shutdown (residual traffic)
#   escalate          — privilege escalation activity (su, sudo abuse)
#   escalated_command — audit events for individual sudo commands by attacker
#   escalated_sudo_command — same as escalated_command; distinct sub-label in audit rules
#   escalated_sudo_session — PAM session opened via sudo by attacker
#   exfiltration-service — exfiltration service activity window (sparse, time-ranged)
#   foothold          — initial access phase: HTTP, VPN, DNS activity
#   network_scan      — PTR queries from nmap local/DMZ scan
#   service_scan      — Apache logs with Nmap user-agent or no user-agent
#   traceroute        — PTR queries generated by traceroute
#   webshell_cmd      — HTTP requests to uploaded webshell URI with attacker params
#   webshell_upload   — HTTP sequence matching 3-step webshell upload flow
#   wpscan            — DNS/HTTP traffic generated by WPScan tool

ANOMALOUS_LABELS: FrozenSet[str] = frozenset({
    "attacker",
    "attacker_http",
    "attacker_vpn",
    "attacker_change_user",
    "crack_passwords",
    "dirb",
    "dns_scan",
    "dnsteal",
    "dnsteal-received",
    "dnsteal-dropped",
    "escalate",
    "escalated_command",
    "escalated_sudo_command",
    "escalated_sudo_session",
    "exfiltration-service",
    "foothold",
    "network_scan",
    "service_scan",
    "traceroute",
    "webshell_cmd",
    "webshell_upload",
    "wpscan",
})

# ── UNCERTAIN labels ──────────────────────────────────────────────────────────
# Labels that appear in the data but are NOT in any rules/ YAML file, or
# whose classification is ambiguous. These are preserved in the output
# DataFrame under the `uncertain_labels` column and excluded from training.
# Currently empty for these three datasets — all 22 found labels are
# documented in rules/ YAML files and are confirmed attacker activity.
UNCERTAIN_LABELS: FrozenSet[str] = frozenset()

# ── NORMAL (unlabeled) ────────────────────────────────────────────────────────
# Log lines with NO label entry in the corresponding labels/ JSON file are
# treated as NORMAL (is_anomaly=0). This is the conservative default.
# IMPORTANT: many gather/ log files have NO matching labels/ file at all —
# all lines in those files are treated as Normal by default.


def classify_labels(labels: list) -> tuple:
    """
    Classify a list of label strings from a labels/ JSON entry.

    Returns:
        (is_anomaly: int, uncertain: list[str])
        - is_anomaly = 1  if any label is in ANOMALOUS_LABELS
        - is_anomaly = 0  if no label is anomalous (all uncertain or none)
        - uncertain       = labels present but not in either set (unknown labels)
    """
    if not labels:
        return 0, []

    anomalous = [l for l in labels if l in ANOMALOUS_LABELS]
    uncertain = [l for l in labels if l not in ANOMALOUS_LABELS and l not in UNCERTAIN_LABELS]

    is_anomaly = 1 if anomalous else 0
    return is_anomaly, uncertain


# ── Feature schema ────────────────────────────────────────────────────────────
# Canonical feature lists for AIT-LDS training.
# severity_level is EXCLUDED because audit showed it is constant (=6, std=0)
# across all three datasets — zero discriminative power.

NUMERICAL_FEATURES = [
    "message_length",    # raw character count of the log message
    "token_count",       # whitespace-split word count
    "digit_ratio",       # fraction of digits in message
    "entropy",           # Shannon entropy of message characters
    # "severity_level" — REMOVED: constant value 6 in all AIT-LDS records
    "has_error",         # keyword: error/fail/failure/fatal/exception/crash
    "has_warning",       # keyword: warn/warning/caution/alert
    "has_auth",          # keyword: auth/login/session/password/sshd/sudo/pam
    "has_failed_auth",   # keyword: failed password/authentication failure/invalid user
    "has_denied",        # keyword: denied/forbidden/unauthorized/rejected/blocked
    "has_ip",            # 1 if an IPv4 address is present in the message
]

CATEGORICAL_FEATURES = [
    "service",           # process/service name extracted by LogParser
]

ALL_FEATURES = NUMERICAL_FEATURES + CATEGORICAL_FEATURES

# ── Behavioral feature schema ─────────────────────────────────────────────────
# Time-window aggregated features computed by BehavioralWindowExtractor.
# These supplement (not replace) the message-level features above.
# Defined here as the single source of truth for training/inference parity.
# See backend/feature_engineering/behavioral_features.py for implementations.

BEHAVIORAL_FEATURES = [
    "beh_total_events",           # total events in window for this grouping key
    "beh_auth_fail_count",        # auth failure events in window
    "beh_auth_success_count",     # auth success events in window
    "beh_fail_success_ratio",     # fail / (fail + success + ε)
    "beh_error_count",            # has_error events in window
    "beh_warning_count",          # has_warning events in window
    "beh_distinct_services",      # distinct service names in window
    "beh_sudo_su_count",          # sudo/su keyword events in window
    "beh_privilege_count",        # privilege-change keyword events in window
    "beh_distinct_ips",           # distinct source IPs in window
    "beh_rare_event_ratio",       # proportion of rare log_type×service combos
    "beh_event_freq_delta",       # z-score vs historical baseline
    "beh_cold_start",             # 1 if no baseline history for this grouping key
]

# Combined feature set for behavioral model training
ALL_BEHAVIORAL_FEATURES = ALL_FEATURES + BEHAVIORAL_FEATURES

# ── Deduplication key ─────────────────────────────────────────────────────────
# Two log lines are considered duplicates if they share the same raw content
# (MD5 hash of stripped line text). Rotated log files (auth.log.1, syslog.2)
# are the primary source of duplicates in these datasets.
#
# Conflict resolution: if the same raw line appears in TWO label files with
# DIFFERENT labels (e.g., Normal in one file and Anomalous in another),
# the record is kept with is_anomaly=1 (conservative: trust the labeled version)
# and flagged in the `duplicate_conflict` column.
DEDUP_KEY = "raw_line_md5"
